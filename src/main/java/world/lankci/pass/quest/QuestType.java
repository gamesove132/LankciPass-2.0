package world.lankci.pass.quest;

/** Типи завдань. Усі, крім COMPLETE_QUESTS, нараховуються подіями Bukkit у світі потрібного режиму. */
public enum QuestType {
    /** Убити мобів (фільтр entities; порожній = будь-які). */
    KILL_MOB,
    /** Убити мобів N різних видів (прогрес = кількість унікальних видів). */
    KILL_UNIQUE_MOB,
    /** Убити інших гравців (лише вбивства, прийняті антиексплойт-перевіркою PvP). */
    KILL_PLAYER,
    /** Зламати блоки (фільтр materials; порожній = будь-які). */
    BREAK_BLOCK,
    /** Виловити рибу/предмети вудкою. */
    FISH,
    /** Скрафтити предмети (фільтр materials). */
    CRAFT_ITEM,
    /** Провести N хвилин у світі режиму. */
    PLAY_MINUTES,
    /** Виконати N звичайних квестів цього ж режиму (для мега-квестів). */
    COMPLETE_QUESTS
}
